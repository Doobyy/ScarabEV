import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const sourceDir = join(process.cwd(), "admin-ui-src", "scripts");
const targetDir = join(process.cwd(), "src", "admin", "scripts");

if (!existsSync(sourceDir)) {
  console.error(`Missing source dir: ${sourceDir}`);
  process.exit(1);
}

const tsFiles = readdirSync(targetDir).filter((name) => name.endsWith(".ts"));
const exportNameByStem = new Map();
for (const tsFile of tsFiles) {
  const stem = tsFile.replace(/\.ts$/, "");
  const tsPath = join(targetDir, tsFile);
  const tsText = readFileSync(tsPath, "utf8");
  const m = tsText.match(/export const ([A-Z0-9_]+)\s*=\s*String\.raw`/);
  if (m) exportNameByStem.set(stem, m[1]);
}

const sourceFiles = readdirSync(sourceDir).filter((name) => name.endsWith(".js")).sort();
for (const sourceFile of sourceFiles) {
  const stem = sourceFile.replace(/\.js$/, "");
  const exportName = exportNameByStem.get(stem);
  if (!exportName) {
    console.error(`No matching TS export name found for source: ${sourceFile}`);
    process.exit(1);
  }

  const sourcePath = join(sourceDir, sourceFile);
  const jsPayload = readFileSync(sourcePath, "utf8")
    .replace(/\r\n/g, "\n")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");

  const out = `// Auto-generated from admin-ui-src/scripts/${sourceFile}. Do not edit this file directly.\n` +
    `export const ${exportName} = String.raw\`\n${jsPayload}\n\`;\n`;
  writeFileSync(join(targetDir, `${stem}.ts`), out, "utf8");
}

console.log(`Generated ${sourceFiles.length} admin inline script module(s).`);

